// agent-write-registry.mjs — every write path the agent (or the rail acting
// on its output) can reach, declared once. Spec 15.3.
//
// WHY THIS EXISTS. The known defect class is a write that reports success
// while writing nothing: approve_obligation_and_queue updated obligations with
// no rowcount check; decide_agent_run returned 0 as if that were a result.
// A registry entry says what the write does and HOW it proves it did it. The
// paired test reads the migrations and refuses any entry whose latest SQL
// body lacks the guard it declares — and refuses any authenticated write RPC
// that is not declared at all. Adding a write path without a receipt is a
// CI failure, not a bug report.
//
// guard values, in order of strength:
//   row_count — `get diagnostics n = row_count` followed by a raise when it
//               is not the expected number. The write itself is proven.
//   not_found — `if not found then raise`. Same proof, plpgsql shorthand.
//   count     — the function is a GENERATOR: it returns how many rows it
//               inserted and zero is a legitimate answer ("nothing is due").
//               Its receipt is the integer; the sweep that calls it sums them.
//               This is the only guard where zero may mean success.

